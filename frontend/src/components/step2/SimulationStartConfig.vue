  useCustomDays: { type: Boolean, required: true },
  customSimulationDays: { type: Number, required: true },
  autoGeneratedRounds: { type: [Number, null], default: null },
  autoGeneratedDays: { type: [Number, null], default: null },
  hasRegeneratingPersona: { type: Boolean, default: false },
})

const emit = defineEmits([
  'update:useCustomRounds',
  'update:customMaxRounds',
  'update:useCustomDays',
  'update:customSimulationDays',
  'start',
])
</script>

<template>
