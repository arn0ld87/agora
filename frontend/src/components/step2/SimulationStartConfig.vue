          />
          <small class="meta">{{ t('step3.config.customValue') }}</small>
        </span>
      </label>
      <label class="rounds-radio">
        <input type="radio" :value="false" :checked="!useCustomRounds" @change="emit('update:useCustomRounds', false)" />
        <span>
          {{ t('step3.config.rounds') }}: {{ autoGeneratedRounds || '?' }}
          <small class="meta">{{ t('step3.config.automatic') }}</small>
        </span>
      </label>
      <label class="rounds-radio">
        <input type="radio" :value="true" :checked="useCustomRounds" @change="emit('update:useCustomRounds', true)" />
        <span>
          {{ t('step3.config.rounds') }}:
          <input
            :value="customMaxRounds"
            type="number"
            min="1"
            max="500"
            class="rounds-input"
            @input="emit('update:customMaxRounds', Number(($event.target as HTMLInputElement).value))"
          />
          <small class="meta">{{ t('step3.config.customValue') }}</small>
        </span>
      </label>
    </div>

    <div class="actions">
      <Button
        variant="primary"
        arrow
        :disabled="phase < 3 || hasRegeneratingPersona"
        :title="hasRegeneratingPersona ? t('step2.persona.regeneratingBlock') : undefined"
        @click="emit('start')"
      >
        {{ t('step3.controls.start') }}
      </Button>
    </div>
    <p v-if="hasRegeneratingPersona" class="hint hint--warn">
      {{ t('step2.persona.regeneratingBlock') }}
    </p>
  </article>
</template>

